package bidilayout

import (
	"slices"
	"unicode"
	"unicode/utf8"

	"golang.org/x/text/unicode/norm"

	"oshell-desktop/internal/terminal/internal/bidi"
)

// State belongs to a paragraph, including paragraphs retained in scrollback.
type State struct {
	Explicit, Auto, RTL, MirrorBoxes bool
}

var Default = State{Auto: true}

// Cell is one logical grapheme, including its occupied columns. Rows contain
// contiguous cells up to their last non-erased column; blank tail cells are
// generated by the layout. An intentional trailing space remains a real cell.
type Cell struct {
	Column, Width int
	Text          string
}

type VisualCell struct {
	Column, Width int
	// Empty means retain the original grapheme. A single space hides a
	// consumed alef while preserving its logical column.
	Display string
}

type Row struct {
	Cells                            []VisualCell
	LogicalToVisual, VisualToLogical []int
}

// Layout owns its maps. Nil Rows means the identity presentation; RTL still
// records the resolved direction used for optional arrow-key swapping.
type Layout struct {
	Rows []Row
	RTL  bool
}

// Paragraph lays out one complete soft-wrapped paragraph. Call explicit
// mode one row at a time. It returns false for malformed cell geometry or
// oversized input; the caller retains the logical display as Swift does.
func Paragraph(rows [][]Cell, cols int, state State) (Layout, bool) {
	if cols < 1 || len(rows) == 0 || len(rows) > 500 {
		return Layout{RTL: state.RTL}, false
	}
	var cells []Cell
	starts := make([]int, len(rows)+1)
	used := make([]int, len(rows))
	potentialRTL := false
	for y, row := range rows {
		starts[y] = len(cells)
		for _, cell := range row {
			if cell.Column != used[y] || cell.Width < 1 || cell.Width > cols-used[y] || cell.Text == "" {
				return Layout{}, false
			}
			used[y] += cell.Width
			cells = append(cells, cell)
			for _, r := range cell.Text {
				potentialRTL = potentialRTL || rtlTrigger(r)
			}
		}
	}
	starts[len(rows)] = len(cells)
	rtl := state.RTL
	if !state.Explicit && state.Auto {
		rtl = detectDirection(cells, rtl)
	}
	if (!state.Explicit && !potentialRTL && !rtl) || (state.Explicit && !rtl) {
		return Layout{}, true
	}
	var core bidi.Paragraph
	var display []string
	if !state.Explicit {
		probe := make([]rune, len(cells))
		for i, c := range cells {
			probe[i] = probeRune(c.Text)
		}
		direction := bidi.LeftToRight
		if rtl {
			direction = bidi.RightToLeft
		}
		if core.Resolve(probe, direction) != len(probe) {
			return Layout{RTL: rtl}, false
		}
		display = shapeArabic(cells)
	}
	result := Layout{Rows: make([]Row, len(rows)), RTL: rtl}
	for y := range rows {
		row := &result.Rows[y]
		row.LogicalToVisual = make([]int, cols)
		row.VisualToLogical = make([]int, cols)
		visual := 0
		appendCell := func(col, width int, display string) {
			row.Cells = append(row.Cells, VisualCell{col, width, display})
			for offset := 0; offset < width; offset++ {
				row.LogicalToVisual[col+offset] = visual + offset
				row.VisualToLogical[visual+offset] = col
			}
			visual += width
		}
		if rtl {
			for col := cols - 1; col >= used[y]; col-- {
				appendCell(col, 1, "")
			}
		}
		start, end := starts[y], starts[y+1]
		if state.Explicit {
			for i := end - 1; i >= start; i-- {
				c := cells[i]
				appendCell(c.Column, c.Width, mirror(c.Text, state.MirrorBoxes))
			}
		} else {
			order, ok := core.Line(start, end)
			if !ok {
				return Layout{RTL: rtl}, false
			}
			for _, i := range order.Order {
				c, shown := cells[i], display[i]
				if shown == "" && order.Levels[i-start]&1 != 0 {
					shown = mirror(c.Text, state.MirrorBoxes)
				}
				appendCell(c.Column, c.Width, shown)
			}
		}
		if !rtl {
			for col := used[y]; col < cols; col++ {
				appendCell(col, 1, "")
			}
		}
	}
	return result, true
}

// PotentialRTL is a cheap probe for rows that can require paragraph ordering.
func PotentialRTL(r rune) bool { return rtlTrigger(r) }

func rtlTrigger(r rune) bool {
	return r >= 0x590 && r <= 0x8ff || r >= 0xfb1d && r <= 0xfdff ||
		r >= 0xfe70 && r <= 0xfefc || r >= 0x10800 && r <= 0x10fff ||
		r >= 0x1e800 && r <= 0x1efff || r == 0x200f || r == 0x202b || r == 0x202e || r == 0x2067
}

func detectDirection(cells []Cell, fallback bool) bool {
	for _, c := range cells {
		for _, r := range c.Text {
			if r == 0x200f {
				return true
			}
			if r == 0x200e {
				return false
			}
			if unicode.IsLetter(r) || unicode.Is(unicode.Nl, r) || unicode.Is(unicode.Other_Alphabetic, r) {
				return rtlTrigger(r)
			}
		}
	}
	return fallback
}

func probeRune(text string) rune {
	r, _ := utf8.DecodeRuneInString(text)
	if norm.NFC.PropertiesString(text).CCC() != 0 || unicode.Is(unicode.Mn, r) || unicode.Is(unicode.Me, r) {
		return 0xb7
	}
	if r >= 0x620 && r <= 0x64a || r >= 0x66e && r <= 0x66f ||
		r >= 0x671 && r <= 0x6d5 || r == 0x6ee || r == 0x6ef || r >= 0x6fa && r <= 0x6ff ||
		r >= 0x750 && r <= 0x77f || r >= 0x870 && r <= 0x88f || r >= 0x8a0 && r <= 0x8d2 || r == 0x200d {
		return 0x621
	}
	if r > 0xffff {
		if rtlTrigger(r) {
			return 0x200f
		}
		return 0xb7
	}
	return r
}

func mirror(text string, boxes bool) string {
	r, n := utf8.DecodeRuneInString(text)
	if n != len(text) {
		return ""
	}
	if dst, ok := mirrored[r]; ok {
		return string(dst)
	}
	if boxes {
		const pairs = "┌┐└┘├┤┏┓┗┛┣┫╔╗╚╝╠╣╭╮╰╯╒╕╘╛╓╖╙╜╞╡╟╢╴╶╸╺"
		all := []rune(pairs)
		if i := slices.Index(all, r); i >= 0 {
			return string(all[i^1])
		}
	}
	return ""
}
