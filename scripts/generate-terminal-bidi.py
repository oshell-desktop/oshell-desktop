"""Regenerate the terminal's Unicode tables from the audited SwiftTerm source."""
import argparse
import hashlib
from pathlib import Path
import re
import subprocess


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--native-source', required=True, type=Path)
    args = parser.parse_args()
    source = args.native_source / 'Vendor/SwiftTerm/Sources/SwiftTerm/Apple'
    arabic = (source / 'ArabicShapingData.swift').read_text(encoding='utf-8')
    mirrors = (source / 'BidiMirroringData.swift').read_text(encoding='utf-8')
    forms = re.findall(r'(0x[0-9A-Fa-f]+):\s*\((0x[0-9A-Fa-f]+),\s*(0x[0-9A-Fa-f]+),\s*(0x[0-9A-Fa-f]+|nil),\s*(0x[0-9A-Fa-f]+|nil)\)', arabic)
    ranges = re.findall(r'\((0x[0-9A-Fa-f]+)\.\.\.(0x[0-9A-Fa-f]+),\s*\.(\w+)\)', arabic)
    pairs = re.findall(r'(0x[0-9A-Fa-f]+):\s*(0x[0-9A-Fa-f]+)', mirrors)
    if not forms or not ranges or not pairs:
        parser.error('Swift table format changed; review the parser before regenerating')
    kinds = {'none', 'transparent', 'causing', 'right', 'left', 'dual'}
    if any(kind not in kinds for _, _, kind in ranges):
        parser.error('Unknown joining classification')
    digest = hashlib.sha256((arabic + mirrors).encode('utf-8')).hexdigest()
    text = '// Code generated by scripts/generate-terminal-bidi.py. DO NOT EDIT.\n'
    text += f'// Source table SHA-256 (UTF-8/LF): {digest}\n'
    text += '// SwiftTerm MIT license: resources/licenses/SwiftTerm-LICENSE. Unicode data: Unicode-LICENSE.\n\npackage bidilayout\n\n'
    text += 'var joiningRanges = [...]struct {lo, hi rune; kind joiningKind}{\n'
    for lo, hi, kind in ranges:
        text += f'{{{lo}, {hi}, joining{kind.title()}}},\n'
    text += '}\n\nvar arabicForms = map[rune]struct {iso, fin, ini, med rune}{\n'
    for key, *values in forms:
        text += key + ': {' + ','.join('0' if v == 'nil' else v for v in values) + '},\n'
    text += '}\n\nvar mirrored = map[rune]rune{\n'
    for a, b in pairs:
        text += f'{a}:{b},\n'
    text += '}\n'
    dest = Path(__file__).resolve().parent.parent / 'internal/terminal/internal/bidilayout/data.go'
    formatted = subprocess.run(['gofmt'], input=text.encode('utf-8'), capture_output=True, check=True).stdout
    dest.write_bytes(formatted)
    print(f'{len(ranges)} joining ranges, {len(forms)} forms, {len(pairs)} mirrors')


if __name__ == '__main__':
    main()
